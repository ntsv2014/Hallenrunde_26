/* Service Worker: immer zuerst aus dem Netz – beim Server nachfragen statt Browser-Zwischenspeicher
   (GitHub Pages erlaubt sonst bis zu 10 min alte Fassungen). Bei Funkloch die zuletzt geladene Fassung. */
const CACHE = "ntsv-7d-v4";
self.addEventListener("install", e => self.skipWaiting());
self.addEventListener("activate", e => e.waitUntil(
  caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())));
self.addEventListener("fetch", e => {
  if (e.request.method !== "GET" || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(
    fetch(e.request, { cache: "no-cache" }).then(r => {
      const copy = r.clone();
      caches.open(CACHE).then(c => c.put(e.request, copy));
      return r;
    }).catch(() => caches.match(e.request))
  );
});
